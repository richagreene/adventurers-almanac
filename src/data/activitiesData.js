// =============================================================================
// The unified "things a player can DO" library the Oracle SELECTS FROM and the
// Pathfinder cross-references. One row per repeatable method: training methods,
// money-makers, daily loops, market plays, hybrids.
//
// SCOPE (current): the 23 skills already modelled in the almanac + existing
// bosses/slayer/quests/diaries. Sailing and any not-yet-modelled skills are
// intentionally deferred (they'd need new almanac sections) — see the tail of
// this file for the parked Sailing rows.
//
// -----------------------------------------------------------------------------
// STAY-CURRENT ARCHITECTURE — three gp models, in order of "liveness":
//
//   model:'computed'  gp is a FUNCTION of live item prices. Carries a machine-
//                     readable `compute` block so the app recomputes exactly
//                     from the OSRS Wiki prices feed it already loads. Items are
//                     referenced BY NAME (matches the Wiki /mapping `name`), so
//                     nothing depends on hand-typed numeric IDs. This is where
//                     "tracks live prices" literally lives — buy/sell/alch/
//                     process/combine/gather methods.
//   model:'wiki-mmg'  Complex drop-table methods (bosses/raids/slayer). gp is
//                     the Money-Making Guide's published rate; `mmgId` links the
//                     method so it can be re-read on refresh. Snapshot + asOf.
//   model:'scales' /  Capital- or context-dependent (flipping) / hand estimate.
//   model:'estimate'  Always carries asOf + conf.
//
// COMPUTE KINDS (how the app evaluates model:'computed'):
//   {kind:'alch',    castsPerHr, natureRune, scan:[itemName,…]}
//        gp/hr = max over scan of (highalch(item) - price(item) - price(nature)) * castsPerHr
//   {kind:'process', ratePerHr, inputs:[{item,qty}], outputs:[{item,qty}], taxable}
//        per action: sum(outputs·price·taxAdj) - sum(inputs·price); ×ratePerHr
//        (also used for 'combine' buy-and-open and for cost-only methods where
//         outputs:[] → a negative gp, e.g. bones at a gilded altar)
//   {kind:'gather',  ratePerHr, outputs:[{item,qty}]}
//        gp/hr = ratePerHr · price(output) (no input cost)
//   Static item props (highalch, buy-limit) come from the Wiki /mapping; live
//   prices from /latest. tax handled via ACTIVITIES_META.economy.geTax.
//
// -----------------------------------------------------------------------------
// SCHEMA  (per activity)
//   id          string    stable kebab-case slug
//   name        string    display
//   category    enum      pvm · skilling · gathering · processing · passive · flip · minigame
//   subtype     string    finer bucket (boss · runecraft · smithing · run · buy-combine …)
//   members     bool
//   trains      [skillKey] skills this method grants meaningful xp in (drives the
//                          Training lens; empty = pure money/utility). skillKeys
//                          match window.LEDGER_DATA skill naming (lowercase).
//   band        {min,max}  level range the method is a sensible choice for (per its
//                          PRIMARY trained skill) — powers "what to do in between".
//   gp          object|null  income model (see above): {model, rate?, per, conf,
//                          asOf, compute?, mmgId?, note?}. null = no gp dimension.
//   xp          [{skill,rate,per}]  headline xp/hr per trained skill
//   intensity   int 1..5   1 true-AFK … 5 click-perfect;  afk bool;  risk enum
//   loop        {durationMin,perDay}|null  for run/daily loops
//   reqs        {skills{},combat,quests[],items[],other[]}  HARD gates
//   rec         {skills{},items[],quests[]}                 SOFT / recommended
//   advances    {goals[], money 0-5, xpv 0-5, unlockv 0-5, tags[]}
//   unlocks     [string]   concrete content produced/gated (Pathfinder edges)
//   ledgerRef   string?    for bosses: canonical row in LEDGER_DATA.bosses
//   wiki,updated,current
// =============================================================================

